function saveCardExpansionStates(root) {
    const states = { expanded: [], editorOpen: [], memoryShown: [] };
    root?.querySelectorAll('.bb-char-card').forEach(card => {
        const name = card.getAttribute('data-char');
        if (!name) return;
        if (card.classList.contains('expanded')) states.expanded.push(name);
        if (card.classList.contains('editor-open')) states.editorOpen.push(name);
        // «Show more» progress is part of the reading context: remember how many
        // pills each section had revealed so a rebuild triggered by an edit or
        // undo from a pill does not collapse the list back to the default
        // limit. Section identity is the title text (the traits section comes
        // and goes, so a positional index would drift between renders).
        card.querySelectorAll('.bb-memory-section').forEach(section => {
            const btn = section.querySelector('.bb-memory-show-more');
            const key = section.querySelector('.bb-memory-title')?.textContent?.trim();
            if (!btn || !key) return;
            const shown = parseInt(btn.getAttribute('data-shown') || '0', 10);
            if (Number.isFinite(shown) && shown > MEMORY_SHOW_LIMIT) {
                states.memoryShown.push({ name, key, shown });
            }
        });
    });
    return states;
}

function restoreCardExpansionStates(states) {
    if (!states) return;
    states.expanded.forEach(name => {
        const card = document.querySelector(`.bb-char-card[data-char="${CSS.escape(name)}"]`);
        if (card) card.classList.add('expanded');
    });
    // Re-reveal the pills the user had unfolded (expanded cards only: a
    // collapsed card resets to the limit by contract), then fix the «ещё N»
    // button label and state to match. A shorter list (an entry was deleted)
    // clamps to the new total instead of over-revealing.
    for (const { name, key, shown } of states.memoryShown || []) {
        const card = document.querySelector(`.bb-char-card[data-char="${CSS.escape(name)}"]`);
        if (!card || !card.classList.contains('expanded')) continue;
        const section = [...card.querySelectorAll('.bb-memory-section')].find(node =>
            node.querySelector('.bb-memory-title')?.textContent?.trim() === key);
        const btn = section?.querySelector('.bb-memory-show-more');
        if (!btn) continue;
        const total = parseInt(btn.getAttribute('data-total') || '0', 10);
        if (!Number.isFinite(total) || total <= MEMORY_SHOW_LIMIT) continue;
        const target = Math.min(shown, total);
        section.querySelectorAll('.bb-memory-pill').forEach((pill, idx) => {
            if (idx < target) pill.classList.remove('bb-memory-hidden');
        });
        btn.setAttribute('data-shown', String(target));
        const remaining = total - target;
        if (remaining > 0) {
            btn.innerHTML = `<i class="fa-solid fa-chevron-down"></i>${t('ещё')} ${remaining}`;
        } else {
            btn.classList.add('bb-memory-show-more-done');
            btn.innerHTML = `<i class="fa-solid fa-chevron-up"></i>${t('свернуть')}`;
        }
    }
    states.editorOpen.forEach(name => {
        const card = document.querySelector(`.bb-char-card[data-char="${CSS.escape(name)}"]`);
        // The block editor is appended on demand (not part of the card
        // template), so a plain classList.add would leave the button marked
        // as expanded with no editor in the DOM after a HUD rebuild. Route
        // through setCharacterEditorOpen to re-create the editor markup and
        // refresh its inputs from the current state (fork-equivalent restore).
        if (card) setCharacterEditorOpen(jQuery(card), true, { skipEditorScroll: true });
    });
}

/**
 * Long character names: measure the real text width (Range API — scrollWidth
 * is unreliable with overflow:visible) and enable a marquee scroll only for
 * names wider than their container.
 */
function detectNameOverflow() {
    document.querySelectorAll('.bb-char-name-compact').forEach(nameEl => {
        const container = nameEl.parentElement;
        if (!container) return;
        const containerWidth = container.clientWidth;
        const range = document.createRange();
        range.selectNodeContents(nameEl);
        const nameWidth = range.getBoundingClientRect().width;

        if (nameWidth > containerWidth + 2) {
            const scrollDist = nameWidth - containerWidth;
            const duration = Math.max(6, Math.min(18, scrollDist / 12));
            nameEl.style.setProperty('--bb-name-scroll', `-${scrollDist}px`);
            nameEl.style.setProperty('--bb-name-dur', `${duration}s`);
            nameEl.classList.add('bb-name-overflow');
        } else {
            nameEl.classList.remove('bb-name-overflow');
            nameEl.style.removeProperty('--bb-name-scroll');
            nameEl.style.removeProperty('--bb-name-dur');
        }
    });
}

/**
 * Updates the HUD disabled-state visuals: status dot, tabs visibility, content
 * overlay (ported from the Extended fork — tracker off keeps the HUD reachable).
 * @param {boolean} isDisabled
 */
function updateHudDisabledState(isDisabled) {
    const liveDot = document.querySelector('.bb-hud-live-dot');
    const tabs = document.querySelector('.bb-hud-tabs');
    const contents = document.querySelectorAll('.bb-hud-content');
    const hud = document.getElementById('bb-social-hud');

    if (isDisabled) {
        if (liveDot) {
            liveDot.classList.add('disabled');
            liveDot.innerHTML = `<i class="fa-solid fa-circle"></i> ${t('отключено')}`;
        }
        if (tabs) tabs.classList.add('bb-hud-tabs--hidden');
        // Show disabled overlay in all content panels
        contents.forEach(c => {
            c.innerHTML = `<div class="bb-hud-disabled-overlay"><button type="button" class="bb-hud-disabled-icon" title="${escapeHtml(t('Включить расширение'))}"><i class="fa-solid fa-power-off"></i></button><div class="bb-hud-disabled-title">${t('Расширение отключено')}</div><div class="bb-hud-disabled-text">${t('Нажмите на индикатор статуса или кнопку выше, чтобы включить')}</div></div>`;
        });
        hud?.classList.add('bb-hud--disabled');
    } else {
        if (liveDot) {
            liveDot.classList.remove('disabled');
            liveDot.innerHTML = `<i class="fa-solid fa-circle"></i> ${t('активно')}`;
        }
        if (tabs) tabs.classList.remove('bb-hud-tabs--hidden');
        hud?.classList.remove('bb-hud--disabled');
    }
}

