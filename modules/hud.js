function readRelationshipEventEditValues(container) {
    const number = selector => {
        const raw = container.querySelector(selector)?.value?.trim();
        if (!raw) return 0;
        const parsed = Number(raw);
        return Number.isFinite(parsed) ? Math.trunc(parsed) : NaN;
    };
    return {
        reason: container.querySelector('.bb-event-edit-reason')?.value || '',
        mood: container.querySelector('.bb-event-edit-mood')?.value || '',
        friendshipDelta: number('.bb-event-edit-friendship'),
        romanceDelta: number('.bb-event-edit-romance'),
    };
}

function reportRelationshipEventError(error) {
    if (error === 'EVENT_NOT_FOUND') notifyError(t('Событие не найдено. Список обновился — переоткройте журнал.'));
    else if (error === 'EDITOR_VALUE') notifyError(t('Баллы должны быть целыми числами от −100 до +100.'));
    else if (error === 'EDITOR_TEXT') notifyError(t('Проверьте длину причины и эмоции.'));
    else notifyError(t('Сцена или записи изменились. Попробуйте ещё раз.'));
}

/**
 * Animated diary stamp cycle (ported from the Extended fork): the stamp label
 * periodically flips to the «¿quieres?» delete affordance; hovering locks the
 * delete state, and while the card is being edited the stamp stays red.
 */
function startStampCycle(root = document) {
    root.querySelectorAll?.('.bb-moment-stamp-deletable').forEach(stamp => {
        if (stamp._bbStampTimers) stamp._bbStampTimers.forEach(timer => clearTimeout(timer));
        stamp._bbStampTimers = [];
        stamp._bbStampHovered = false;

        const addTimer = (fn, ms) => {
            const id = setTimeout(() => {
                stamp._bbStampTimers = stamp._bbStampTimers.filter(timer => timer !== id);
                // A HUD rebuild detaches old stamps while their cycle is
                // pending. Stop the chain on dead nodes instead of letting it
                // reschedule forever (each render would leak another chain).
                if (!stamp.isConnected) { clearTimers(); return; }
                fn();
            }, ms);
            stamp._bbStampTimers.push(id);
            return id;
        };
        const clearTimers = () => {
            (stamp._bbStampTimers || []).forEach(timer => clearTimeout(timer));
            stamp._bbStampTimers = [];
        };
        const scheduleCycle = () => {
            if (stamp._bbStampHovered) return;
            // 3s label, then show delete (1s CSS transition)
            addTimer(() => {
                if (stamp._bbStampHovered) return;
                stamp.classList.add('bb-stamp-show-delete');
                // Hold delete for ~2s (1s transition + 1s hold)
                addTimer(() => {
                    if (stamp._bbStampHovered) return;
                    stamp.classList.remove('bb-stamp-show-delete');
                    // After 1s transition back, restart cycle
                    addTimer(scheduleCycle, 1000);
                }, 2000);
            }, 3000);
        };

        scheduleCycle();

        // Listeners are attached once per element: startStampCycle may be
        // re-invoked on existing stamps after an edit form closes.
        if (!stamp._bbStampListeners) {
            stamp._bbStampListeners = true;
            stamp.addEventListener('mouseenter', () => {
                stamp._bbStampHovered = true;
                clearTimers();
                stamp.classList.remove('bb-stamp-show-delete');
                stamp.classList.add('bb-stamp-hovered');
            });
            stamp.addEventListener('mouseleave', () => {
                stamp._bbStampHovered = false;
                stamp.classList.remove('bb-stamp-hovered');
                // After 1s transition back to the label, restart the cycle
                addTimer(scheduleCycle, 1000);
            });
        }
    });
}

function bindRelationshipEventButtons(root) {
    if (!root) return;

    // Diary stamp click → disable the source event (fork's «¿quieres?» flow,
    // routed through the non-destructive upstream editor engine).
    root.querySelectorAll('.bb-moment-stamp-deletable').forEach(stamp => {
        stamp.addEventListener('click', async e => {
            e.stopPropagation();
            const item = stamp.closest('[data-event-key]');
            if (!item || item.classList.contains('event-editing')) return;
            let confirmed = false;
            try {
                confirmed = await SillyTavern.getContext().callPopup(
                    `<h3>${t('Отключить событие?')}</h3><p>${t('Событие будет отключено. Статы пересчитаются автоматически. Вернуть отключённое можно через редактор отношений в консоли разработчика.')}</p>`,
                    'confirm'
                );
            } catch { confirmed = false; }
            if (!confirmed) return;
            const result = applyRelationshipEventEdit(item.dataset.eventKey, 'disable', {});
            if (result.ok && result.changed) notifySuccess(t('Запись отключена.'));
            else if (!result.ok) reportRelationshipEventError(result.error);
        });
    });

    root.querySelectorAll('.bb-glog-edit-btn, .bb-moment-edit-btn').forEach(button => {
        button.addEventListener('click', e => {
            e.stopPropagation();
            const item = button.closest('[data-event-key]');
            if (!item || item.classList.contains('event-editing')) return;
            const entry = getRelationshipEventByKey(item.dataset.eventKey);
            if (!entry) { notifyInfo(t('Событие больше не отслеживается в этой сцене.')); return; }

            item.classList.add('event-editing');
            // Editing lock for the animated stamp (card stays in the red state).
            const stamp = item.querySelector('.bb-moment-stamp-deletable');
            if (stamp) {
                stamp._bbStampHovered = true;
                if (stamp._bbStampTimers) {
                    stamp._bbStampTimers.forEach(timer => clearTimeout(timer));
                    stamp._bbStampTimers = [];
                }
                stamp.classList.remove('bb-stamp-show-delete');
                stamp.classList.add('bb-stamp-hovered');
            }
            const host = item.classList.contains('bb-moment-card') ? item.querySelector('.bb-moment-body') : item;
            const textEl = host.querySelector('.bb-glog-text, .bb-moment-text');
            if (textEl) textEl.style.display = 'none';
            // The undo affordance appears together with save/cancel and
            // disappears with the form — the edit button returns to its place
            // on save/cancel (fork behavior). Both journal and diary forms
            // carry it; the corner undo chip hides while the form is open.
            host.insertAdjacentHTML('beforeend', buildRelationshipEventEditForm(entry, { withUndo: true }));

            const form = host.querySelector('.bb-event-edit-form');
            const closeForm = () => {
                form?.remove();
                if (textEl) textEl.style.display = '';
                item.classList.remove('event-editing');
                // Release the stamp lock and restart its cycle.
                if (stamp) {
                    stamp._bbStampHovered = false;
                    stamp.classList.remove('bb-stamp-hovered');
                    setTimeout(() => {
                        if (!item.classList.contains('event-editing')) startStampCycle(item.closest('.bb-hud-content') || item.parentElement || document);
                    }, 1000);
                }
            };
            form.querySelector('.bb-event-cancel-btn').addEventListener('click', closeForm);
            form.querySelector('.bb-glog-undo-btn')?.addEventListener('click', () => {
                const result = applyRelationshipEventEdit(item.dataset.eventKey, 'undo', {});
                if (result.ok && result.changed) notifySuccess(t('Правка отменена.'));
                else if (result.ok) notifyInfo(t('Нечего отменять.'));
                else reportRelationshipEventError(result.error);
                closeForm();
            });
            // Fourth action chip: same flow as the item's corner delete button
            // (confirm popup → non-destructive disable through the engine).
            form.querySelector('.bb-event-delete-btn')?.addEventListener('click', async () => {
                let confirmed = false;
                setHudPopupPriority(true);
                try {
                    confirmed = await SillyTavern.getContext().callPopup(
                        `<h3>${t('Отключить событие?')}</h3><p>${t('Событие будет отключено. Статы пересчитаются автоматически. Вернуть отключённое можно через редактор отношений в консоли разработчика.')}</p>`,
                        'confirm'
                    );
                } catch { confirmed = false; } finally { setHudPopupPriority(false); }
                if (!confirmed) return;
                const result = applyRelationshipEventEdit(item.dataset.eventKey, 'disable', {});
                if (result.ok && result.changed) notifySuccess(t('Событие отключено.'));
                else if (!result.ok) reportRelationshipEventError(result.error);
                closeForm();
            });
            form.querySelector('.bb-event-save-btn').addEventListener('click', () => {
                const values = readRelationshipEventEditValues(form);
                const result = applyRelationshipEventEdit(item.dataset.eventKey, 'edit', values);
                if (result.ok && result.changed) notifySuccess(t('Событие обновлено. Статы пересчитаны.'));
                else if (result.ok) notifyInfo(t('Нет изменений.'));
                else reportRelationshipEventError(result.error);
                closeForm();
            });
        });
    });

    root.querySelectorAll('.bb-glog-delete-btn').forEach(button => {
        button.addEventListener('click', async e => {
            e.stopPropagation();
            const item = button.closest('[data-event-key]');
            if (!item) return;
            let confirmed = false;
            setHudPopupPriority(true);
            try {
                confirmed = await SillyTavern.getContext().callPopup(
                    `<h3>${t('Отключить событие?')}</h3><p>${t('Событие будет отключено. Статы пересчитаются автоматически. Вернуть отключённое можно через редактор отношений в консоли разработчика.')}</p>`,
                    'confirm'
                );
            } catch { confirmed = false; } finally { setHudPopupPriority(false); }
            if (!confirmed) return;
            const result = applyRelationshipEventEdit(item.dataset.eventKey, 'disable', {});
            if (result.ok && result.changed) notifySuccess(t('Событие отключено.'));
            else if (!result.ok) reportRelationshipEventError(result.error);
        });
    });

    // Inline undo duplicate (journal items + diary cards): reverts the last
    // edit of the event without opening the edit form. The diary chip is
    // stacked above the edit pencil so the description box keeps its width.
    root.querySelectorAll('.bb-glog-undo-inline, .bb-moment-undo-btn').forEach(button => {
        button.addEventListener('click', e => {
            e.stopPropagation();
            const item = button.closest('[data-event-key]');
            if (!item) return;
            const result = applyRelationshipEventEdit(item.dataset.eventKey, 'undo', {});
            if (result.ok && result.changed) notifySuccess(t('Правка отменена.'));
            else if (result.ok) notifyInfo(t('Нечего отменять.'));
            else reportRelationshipEventError(result.error);
        });
    });
}

/**
 * Memory-pill edit/delete buttons (ported from the Extended fork, routed
 * through the upstream memory-editor engine): edit opens an inline textarea
 * inside the pill; delete hides the record non-destructively (undoable).
 */
function bindMemoryPillHandlers(root = document) {
    const readPillRecord = pill => {
        const card = pill.closest('.bb-char-card');
        const charName = card?.getAttribute('data-char') || '';
        const editorIndex = parseInt(pill.getAttribute('data-editor-index'), 10);
        if (!charName || !Number.isFinite(editorIndex)) return null;
        return memoryEditorEntries(charName).find(record => record.index === editorIndex) || null;
    };

    const reportMemoryError = error => {
        if (error?.message === 'EDITOR_TEXT') notifyError(t('Проверьте длину текста. Для черты используйте «Название: описание».'));
        else notifyError(t('Сцена или записи изменились. Откройте карточку заново.'));
    };

    root.querySelectorAll('.bb-memory-pill .bb-memory-edit-btn').forEach(button => {
        button.addEventListener('click', e => {
            e.stopPropagation();
            const pill = button.closest('.bb-memory-pill');
            if (!pill || pill.classList.contains('editing')) return;
            const record = readPillRecord(pill);
            if (!record) { notifyInfo(t('Запись больше не отслеживается в этой сцене.')); return; }

            const textSpan = pill.querySelector('span:not(.bb-memory-pill-btns):not(.bb-mem-deltas):not(.bb-memory-btn-row)');
            pill.classList.add('editing');
            // Only the pencil gives way to the inline form; the button container
            // (and the trash in its bottom-right slot) stays visible so the
            // record can be deleted mid-edit from the same corner.
            const btns = pill.querySelector('.bb-memory-pill-btns');
            const editBtn = btns?.querySelector('.bb-memory-edit-btn');
            if (editBtn) editBtn.style.display = 'none';
            if (textSpan) textSpan.style.display = 'none';

            const editHtml = `<div class="bb-memory-inline-edit">
                <textarea class="text_pole bb-memory-edit-text" rows="1">${escapeHtml(record.text)}</textarea>
                <div class="bb-inline-edit-actions">
                    <button type="button" class="bb-memory-save-btn" title="${escapeHtml(t('Сохранить'))}"><i class="fa-solid fa-check"></i></button>
                    <button type="button" class="bb-memory-cancel-btn" title="${escapeHtml(t('Отмена'))}"><i class="fa-solid fa-xmark"></i></button>
                </div>
            </div>`;
            pill.insertAdjacentHTML('beforeend', editHtml);

            const editTextarea = pill.querySelector('.bb-memory-edit-text');
            const autoResize = () => {
                editTextarea.style.height = 'auto';
                editTextarea.style.height = `${editTextarea.scrollHeight}px`;
            };
            editTextarea.addEventListener('input', autoResize);
            setTimeout(autoResize, 0);
            editTextarea.focus();

            const restorePill = () => {
                pill.querySelector('.bb-memory-inline-edit')?.remove();
                pill.classList.remove('editing');
                if (editBtn) editBtn.style.display = '';
                if (textSpan) textSpan.style.display = '';
            };

            pill.querySelector('.bb-memory-cancel-btn').addEventListener('click', ev => {
                ev.stopPropagation();
                restorePill();
            });

            pill.querySelector('.bb-memory-save-btn').addEventListener('click', ev => {
                ev.stopPropagation();
                const kind = pill.getAttribute('data-editor-kind') || 'deep';
                const newText = String(editTextarea.value || '').trim();
                try {
                    const fresh = readPillRecord(pill);
                    if (!fresh || fresh.revision !== record.revision) throw new Error('EDITOR_STALE');
                    if (kind === 'trait' && !newText.includes(':')) throw new Error('EDITOR_TEXT');
                    if (newText.length > (kind === 'trait' ? 240 : 2000)) throw new Error('EDITOR_TEXT');
                    if (!applyMemoryEntryAction(record, 'edit', newText)) return;
                    saveChatDebounced();
                    recalculateAllStats(false);
                    notifySuccess(t(kind === 'trait' ? 'Черта обновлена!' : 'Воспоминание обновлено!'));
                } catch (error) {
                    reportMemoryError(error);
                }
            });
        });
    });

    root.querySelectorAll('.bb-memory-pill .bb-memory-undo-btn').forEach(button => {
        button.addEventListener('click', e => {
            e.stopPropagation();
            const pill = button.closest('.bb-memory-pill');
            if (!pill) return;
            const record = readPillRecord(pill);
            if (!record) { notifyInfo(t('Запись больше не отслеживается в этой сцене.')); return; }
            try {
                if (!applyMemoryEntryAction(record, 'undo')) { notifyInfo(t('Нечего отменять.')); return; }
                saveChatDebounced();
                recalculateAllStats(false);
                notifySuccess(t('Правка отменена.'));
            } catch (error) {
                reportMemoryError(error);
            }
        });
    });

    root.querySelectorAll('.bb-memory-pill .bb-memory-delete-btn').forEach(button => {
        button.addEventListener('click', async e => {
            e.stopPropagation();
            const pill = button.closest('.bb-memory-pill');
            if (!pill) return;
            const record = readPillRecord(pill);
            if (!record) { notifyInfo(t('Запись больше не отслеживается в этой сцене.')); return; }
            const kind = pill.getAttribute('data-editor-kind') || 'deep';
            const prompt = kind === 'trait'
                ? `<h3>${t('Удалить черту?')}</h3><p>${t('Черта будет скрыта из памяти персонажа. Статы и журнал не изменятся. Удаление можно отменить.')}</p>`
                : memoryRecordEvent(record)
                    ? `<h3>${t('Отключить событие?')}</h3><p>${t('Событие будет отключено. Статы пересчитаются автоматически. Вернуть отключённое можно через редактор отношений в консоли разработчика.')}</p>`
                    : `<h3>${t('Удалить воспоминание?')}</h3><p>${t('След будет скрыт из памяти персонажа. Статы и журнал не изменятся. Удаление можно отменить.')}</p>`;
            let confirmed = false;
            setHudPopupPriority(true);
            try {
                confirmed = await SillyTavern.getContext().callPopup(prompt, 'confirm');
            } catch { confirmed = false; }
            finally { setHudPopupPriority(false); }
            if (!confirmed) return;
            try {
                if (!applyMemoryEntryAction(record, 'delete')) return;
                saveChatDebounced();
                recalculateAllStats(false);
                notifySuccess(t(memoryRecordEvent(record) ? 'Событие отключено.' : kind === 'trait' ? 'Черта удалена!' : 'Воспоминание удалено!'));
            } catch (error) {
                reportMemoryError(error);
            }
        });
    });
}

export function updateHudVisibility() {
    const trackerDisabled = extension_settings[MODULE_NAME]?.disableRelationshipTracker === true;
    const context = SillyTavern.getContext();
    if (!hasContextInitialized(context)) {
        if (!hudVisibilityRetryTimer) {
            hudVisibilityRetryTimer = setTimeout(() => {
                hudVisibilityRetryTimer = null;
                updateHudVisibility();
            }, HUD_VISIBILITY_RETRY_MS);
        }
        return;
    }

    if (hudVisibilityRetryTimer) {
        clearTimeout(hudVisibilityRetryTimer);
        hudVisibilityRetryTimer = null;
    }

    // Fork UX: with the tracker off the HUD stays reachable and renders the
    // disabled overlay (dot → «отключено», tabs hidden) instead of hiding
    // the whole panel, so the re-enable affordance is always one click away.
    updateHudDisabledState(trackerDisabled);
    updateGeneratorToolbarButton();

    const chatId = context?.chatId;
    const chatLength = Array.isArray(context?.chat) ? context.chat.length : 0;
    const isGroup = typeof context?.is_group === 'boolean'
        ? context.is_group
        : typeof context?.groupId !== 'undefined'
            ? Boolean(context.groupId)
            : undefined;
    const chatType = typeof context?.chat_type === 'string'
        ? context.chat_type
        : isGroup === true
            ? 'group'
            : 'direct';
    const shouldShowHud = hasActiveChatContext(context);

    setHudChatVisibility(shouldShowHud);

    if (isDevModeEnabled()) {
        console.debug('[BB VN][debug] HUD visibility updated', {
            action: shouldShowHud ? 'show' : 'hide',
            chatId,
            chatLength,
            isGroup,
            chatType,
        });
    }
    syncToastContainerWithHud();
}

function setHudChatVisibility(visible) {
    if (visible) {
        clearTimeout(hudExitTimer);
        hudExitTimer = null;
        document.body.classList.remove('bb-social-chat-leaving');
        document.body.classList.add('bb-social-chat-visible');
        return;
    }
    if (hudExitTimer) return;
    const hud = document.getElementById('bb-social-hud');
    const wasOpen = hud?.classList.contains('open') || hud?.classList.contains('is-panel-dragging');
    closeSocialHud();
    if (!document.body.classList.contains('bb-social-chat-visible')) return;
    if (window.matchMedia('(prefers-reduced-motion: reduce)').matches) {
        document.body.classList.remove('bb-social-chat-visible');
        return;
    }
    const fadeTab = () => {
        document.body.classList.add('bb-social-chat-leaving');
        hudExitTimer = setTimeout(() => {
            hudExitTimer = null;
            document.body.classList.remove('bb-social-chat-visible', 'bb-social-chat-leaving');
        }, 200);
    };
    if (wasOpen) hudExitTimer = setTimeout(fadeTab, 340);
    else fadeTab();
}

let hudSlideProgress = 0;
let hudSlideFrame = null;

function stopHudSlideAnimation() {
    if (hudSlideFrame !== null) cancelAnimationFrame(hudSlideFrame);
    hudSlideFrame = null;
}

function setHudSlideProgress(progress) {
    const hud = document.getElementById('bb-social-hud');
    const content = hud?.querySelector('.bb-hud-slide-content');
    const toggle = document.getElementById('bb-social-hud-toggle');
    hudSlideProgress = Math.max(0, Math.min(1, progress));
    if (!hud || !content || !toggle) return;
    const hiddenPercent = (1 - hudSlideProgress) * 100;
    hud.style.clipPath = `inset(0 0 0 ${hiddenPercent}%)`;
    content.style.transform = `translateX(${hiddenPercent}%)`;
    toggle.style.transform = `translateX(${-hud.getBoundingClientRect().width * hudSlideProgress}px)`;
}

function animateHudSlideTo(target) {
    stopHudSlideAnimation();
    if (window.matchMedia('(prefers-reduced-motion: reduce)').matches) {
        setHudSlideProgress(target);
        return;
    }
    const start = hudSlideProgress;
    const startedAt = performance.now();
    const frame = now => {
        const elapsed = Math.min(1, (now - startedAt) / 340);
        const eased = elapsed * elapsed * (3 - 2 * elapsed);
        setHudSlideProgress(start + (target - start) * eased);
        hudSlideFrame = elapsed < 1 ? requestAnimationFrame(frame) : null;
    };
    hudSlideFrame = requestAnimationFrame(frame);
}

export function openSocialHud() {
    jQuery('#bb-social-hud')
        .removeClass('is-panel-dragging')
        .addClass('open');
    jQuery('#bb-social-hud-backdrop').addClass('open');
    jQuery('body').addClass('bb-social-hud-active');
    jQuery('#bb-social-toast-container').addClass('hud-open');
    jQuery('#bb-hud-arrow').removeClass('fa-chevron-left').addClass('fa-chevron-right');
    renderSocialHud();
    animateHudSlideTo(1);
    syncToastContainerWithHud();
}

export function closeSocialHud() {
    requestCloseToolbarPopup();
    jQuery('#bb-social-hud').removeClass('is-panel-dragging open');
    jQuery('#bb-social-hud-backdrop').removeClass('open');
    jQuery('body').removeClass('bb-social-hud-active');
    animateHudSlideTo(0);
    jQuery('#bb-social-toast-container').removeClass('hud-open');
    jQuery('#bb-hud-arrow').removeClass('fa-chevron-right').addClass('fa-chevron-left');
    syncToastContainerWithHud();
}

export function ensureHudContainer() {
    if (document.getElementById('bb-social-hud')) return;
    const hudHtml = ui`
        <button type="button" id="bb-social-hud-backdrop" aria-label="Закрыть HUD"></button>
        <button type="button" id="bb-social-hud-mobile-launcher" aria-label="Открыть HUD"><i class="fa-solid fa-users-viewfinder"></i><span>VNE</span></button>
        <div id="bb-social-hud">
            <div class="bb-hud-slide-content">
                <div class="bb-hud-header"><div class="bb-hud-header-top"><span class="bb-hud-badge">Visual Novel Engine</span><div class="bb-hud-status-row"><span class="bb-hud-live-dot"><i class="fa-solid fa-circle"></i> активно</span><button type="button" class="bb-hud-mobile-close" aria-label="Закрыть HUD"><i class="fa-solid fa-xmark"></i></button></div></div><div class="bb-hud-title-row"><div class="bb-hud-title">VNE</div>${buildToolbarHtml()}</div><div class="bb-hud-subtitle">связи · журнал · дневник событий</div></div>
                <div class="bb-hud-tabs"><div class="bb-hud-tab active" data-tab="chars"><i class="fa-solid fa-heart-pulse"></i><span>Связи</span></div><div class="bb-hud-tab" data-tab="log"><i class="fa-solid fa-terminal"></i><span>Система</span></div><div class="bb-hud-tab" data-tab="moments"><i class="fa-solid fa-book-open"></i><span>Дневник</span></div></div>
                <div class="bb-hud-content active" id="bb-hud-chars"></div><div class="bb-hud-content" id="bb-hud-log"></div><div class="bb-hud-content" id="bb-hud-moments"></div>
            </div>
        </div>
        <div id="bb-social-hud-toggle" title="VNE HUD"><i class="fa-solid fa-users-viewfinder"></i><span class="bb-toggle-label">VNE</span><i class="fa-solid fa-chevron-left" id="bb-hud-arrow"></i></div>
    `;
    jQuery('body').append(hudHtml);

    // Floating toolbar popups (root stacking context, see toolbar-popup.js).
    ensureToolbarPopupSystem();

    // Diary rendering modes (text smoothing / GPU compositing) from settings.
    applyMomentRenderClasses();

    const toggle = document.getElementById('bb-social-hud-toggle');
    const hud = document.getElementById('bb-social-hud');
    const positionKey = 'bb-visual-novel-engine-toggle-top';
    let dragState = null;
    const clampToggleTop = top => {
        const height = toggle?.getBoundingClientRect().height || 84;
        return Math.max(8, Math.min(Math.max(8, window.innerHeight - height - 8), top));
    };
    const applySavedTogglePosition = () => {
        if (!toggle) return;
        const raw = Number.parseFloat(localStorage.getItem(positionKey));
        const top = Number.isFinite(raw) ? clampToggleTop(raw) : clampToggleTop(130);
        toggle.style.setProperty('--bb-social-toggle-top', `${Math.round(top)}px`);
    };
    applySavedTogglePosition();
    toggle?.addEventListener('pointerdown', event => {
        if (event.button !== undefined && event.button !== 0) return;
        dragState = { pointerId: event.pointerId, startX: event.clientX, startY: event.clientY, startTop: toggle.getBoundingClientRect().top, startProgress: hudSlideProgress, mode: null, moved: false };
        toggle.setPointerCapture?.(event.pointerId);
    });
    toggle?.addEventListener('pointermove', event => {
        if (!dragState || event.pointerId !== dragState.pointerId) return;
        const deltaX = event.clientX - dragState.startX;
        const delta = event.clientY - dragState.startY;
        if (!dragState.mode && Math.max(Math.abs(deltaX), Math.abs(delta)) < 5) return;
        if (!dragState.mode) dragState.mode = Math.abs(deltaX) > Math.abs(delta) ? 'panel' : 'position';
        dragState.moved = true;
        if (dragState.mode === 'panel') {
            const panelWidth = hud.getBoundingClientRect().width || 390;
            const progress = Math.max(0, Math.min(1, dragState.startProgress - deltaX / panelWidth));
            stopHudSlideAnimation();
            setHudSlideProgress(progress);
            hud.classList.add('is-panel-dragging');
            return;
        }
        toggle.classList.add('is-dragging');
        toggle.style.setProperty('--bb-social-toggle-top', `${Math.round(clampToggleTop(dragState.startTop + delta))}px`);
    });
    const finishToggleDrag = event => {
        if (!dragState || event.pointerId !== dragState.pointerId) return;
        if (dragState.mode === 'panel') {
            const progress = hudSlideProgress;
            if (progress >= 0.45) openSocialHud(); else closeSocialHud();
            hud.classList.remove('is-panel-dragging');
            toggle.dataset.dragged = 'true';
        } else if (dragState.moved) {
            const top = clampToggleTop(toggle.getBoundingClientRect().top);
            toggle.style.setProperty('--bb-social-toggle-top', `${Math.round(top)}px`);
            localStorage.setItem(positionKey, String(Math.round(top)));
            toggle.dataset.dragged = 'true';
        }
        toggle.classList.remove('is-dragging');
        hud.classList.remove('is-panel-dragging');
        dragState = null;
    };
    toggle?.addEventListener('pointerup', finishToggleDrag);
    toggle?.addEventListener('pointercancel', finishToggleDrag);

    jQuery('.bb-hud-tab').on('click', function() {
        jQuery('.bb-hud-tab').removeClass('active'); jQuery('.bb-hud-content').removeClass('active');
        jQuery(this).addClass('active'); jQuery(`#bb-hud-${jQuery(this).data('tab')}`).addClass('active');
    });

    jQuery('#bb-social-hud-toggle, #bb-social-hud-mobile-launcher').on('click', function() {
        if (this.dataset.dragged === 'true') {
            delete this.dataset.dragged;
            return;
        }
        if (jQuery('#bb-social-hud').hasClass('open')) closeSocialHud(); else openSocialHud();
    });

    jQuery('#bb-social-hud-backdrop, .bb-hud-mobile-close').on('click', closeSocialHud);

    // Status dot / disabled-overlay toggle (enable/disable relationship
    // tracker, fork UX). Delegated: the overlay re-renders its inner HTML.
    jQuery(document)
        .off('click.bbHudLiveDot', '.bb-hud-live-dot')
        .on('click.bbHudLiveDot', '.bb-hud-live-dot', function(e) {
            e.stopPropagation();
            toggleExtensionEnabled();
        })
        .off('click.bbHudDisabledIcon', '.bb-hud-disabled-icon')
        .on('click.bbHudDisabledIcon', '.bb-hud-disabled-icon', function(e) {
            e.stopPropagation();
            toggleExtensionEnabled();
        });
    // Apply the initial disabled state on container creation.
    if (extension_settings[MODULE_NAME]?.disableRelationshipTracker === true) {
        updateHudDisabledState(true);
    }

    let timer = null;
    const scheduleIdle = () => {
        if (!toggle) return; clearTimeout(timer); toggle.classList.remove('bb-toggle-idle');
        if (window.innerWidth <= 760) timer = setTimeout(() => toggle.classList.add('bb-toggle-idle'), 1500);
    };
    scheduleIdle();
    if (toggle) ['pointerdown', 'touchstart', 'mouseenter', 'focus'].forEach(ev => toggle.addEventListener(ev, scheduleIdle));

    window.addEventListener('resize', () => {
        applySavedTogglePosition();
        setHudSlideProgress(hudSlideProgress);
        if (window.innerWidth > 760) jQuery('#bb-social-hud-backdrop').removeClass('open');
        syncToastContainerWithHud(); scheduleIdle();
    });
}
