// Memory pill pagination: show the first N pills per section, reveal the rest
// in steps («ещё N»), collapse back to the limit when the card collapses.
const MEMORY_SHOW_LIMIT = 4;
const MEMORY_SHOW_MORE = 4;

function paginateMemoryPills(pillHtmlArray) {
    const html = pillHtmlArray.map((pillHtml, index) => {
        if (index < MEMORY_SHOW_LIMIT) return pillHtml;
        return pillHtml.replace('class="bb-memory-pill', 'class="bb-memory-pill bb-memory-hidden');
    }).join('');
    if (pillHtmlArray.length <= MEMORY_SHOW_LIMIT) return { html, showMoreBtn: '' };
    const remaining = pillHtmlArray.length - MEMORY_SHOW_LIMIT;
    const showMoreBtn = `<button type="button" class="bb-memory-show-more" data-shown="${MEMORY_SHOW_LIMIT}" data-step="${MEMORY_SHOW_MORE}" data-total="${pillHtmlArray.length}"><i class="fa-solid fa-chevron-down"></i>${t('ещё')} ${remaining}</button>`;
    return { html, showMoreBtn };
}

function resetMemoryShowMore(card) {
    if (!card || typeof card.find !== 'function') return;
    card.find('.bb-memory-show-more').each(function() {
        const btn = jQuery(this);
        const section = btn.closest('.bb-memory-section');
        const total = parseInt(btn.attr('data-total') || '0', 10);
        section.find('.bb-memory-pill').each(function(idx) {
            if (idx >= MEMORY_SHOW_LIMIT) jQuery(this).addClass('bb-memory-hidden');
        });
        btn.removeClass('bb-memory-show-more-done');
        btn.attr('data-shown', String(MEMORY_SHOW_LIMIT));
        const remaining = total - MEMORY_SHOW_LIMIT;
        if (remaining > 0) {
            btn.html(`<i class="fa-solid fa-chevron-down"></i>${t('ещё')} ${remaining}`);
        }
    });
}

